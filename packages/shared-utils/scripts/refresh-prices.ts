/**
 * Refresh src/pricing/priceTable.ts from the public OpenRouter model lists.
 *
 * Usage: npm run prices:refresh --workspace=packages/shared-utils
 *
 * Both endpoints are public GET requests and need no key. The script writes
 * a TypeScript module rather than JSON so that the built package loads it
 * in Node and in the browser without import attributes.
 */
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  buildPriceTable,
  OPENROUTER_EMBEDDING_MODELS_URL,
  OPENROUTER_MODELS_URL,
  type OpenRouterModel,
} from '../src/pricing/openRouterMapping';

const OUTPUT = resolve(dirname(fileURLToPath(import.meta.url)), '../src/pricing/priceTable.ts');

async function fetchModels(url: string): Promise<OpenRouterModel[]> {
  const response = await fetch(url, { headers: { Accept: 'application/json' } });
  if (!response.ok) {
    throw new Error(`GET ${url} failed: ${response.status} ${response.statusText}`);
  }
  const body = (await response.json()) as { data?: OpenRouterModel[] };
  if (!Array.isArray(body.data)) {
    throw new Error(`GET ${url} returned no data array`);
  }
  return body.data;
}

async function main(): Promise<void> {
  const lists = await Promise.all([
    fetchModels(OPENROUTER_MODELS_URL),
    fetchModels(OPENROUTER_EMBEDDING_MODELS_URL),
  ]);
  const table = buildPriceTable(lists, new Date());

  const source = `// Generated by scripts/refresh-prices.ts. Do not edit by hand.
// Prices in USD per million tokens, from ${OPENROUTER_MODELS_URL}
// and ${OPENROUTER_EMBEDDING_MODELS_URL}.
import type { PriceTable } from './types';

export const PRICE_TABLE: PriceTable = ${JSON.stringify(table, null, 2)};
`;
  writeFileSync(OUTPUT, source);
  console.log(`Wrote ${Object.keys(table.models).length} prices to ${OUTPUT}`);
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
